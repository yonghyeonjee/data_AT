-- 모델 목록 교체/추가 (관리자) · p_rows: [{model, cat, grp, sub_ok, bonus}] · p_replace=true 면 목록에 없는 모델은 active=false
create or replace function sub.f_pkg_import(p_rows jsonb, p_replace boolean, p_by text) returns jsonb
language plpgsql security definer set search_path to 'pg_catalog','public' as $$
declare v_n int := 0; v_off int := 0; v_before jsonb;
begin
  if jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) = 0 then raise exception '모델 목록이 비었습니다' using errcode = '22023'; end if;
  select jsonb_build_object('n', count(*), 'n_sub', count(*) filter (where sub_ok)) into v_before from sub.pkg_model where active;
  create temp table _pkg_in on commit drop as
    select upper(btrim(x->>'model')) model, btrim(coalesce(x->>'cat','')) cat, nullif(btrim(coalesce(x->>'grp','')),'') grp,
           coalesce((x->>'sub_ok')::boolean, false) sub_ok, coalesce((x->>'bonus')::boolean, false) bonus
      from jsonb_array_elements(p_rows) x
     where coalesce(btrim(x->>'model'),'') <> '';
  if exists (select 1 from _pkg_in where cat = '') then raise exception '품목이 빈 줄이 있습니다 (모델마다 품목이 있어야 합니다)' using errcode = '22023'; end if;
  insert into sub.pkg_model (model, cat, grp, sub_ok, bonus, active, updated_by)
  select distinct on (model) model, cat, grp, sub_ok, bonus, true, p_by from _pkg_in order by model, sub_ok desc
  on conflict (model) do update set cat = excluded.cat, grp = excluded.grp, sub_ok = excluded.sub_ok, bonus = excluded.bonus, active = true,
                                    updated_by = excluded.updated_by, updated_at = now();
  get diagnostics v_n = row_count;
  if p_replace then
    update sub.pkg_model m set active = false, updated_by = p_by, updated_at = now()
     where m.active and not exists (select 1 from _pkg_in i where i.model = m.model);
    get diagnostics v_off = row_count;
  end if;
  insert into sub.policy_log (kind, key, before, after, by_user)
  values ('policy', 'pkg_model', v_before, jsonb_build_object('n', (select count(*) from sub.pkg_model where active), 'n_sub', (select count(*) from sub.pkg_model where active and sub_ok), 'in', v_n, 'off', v_off, 'replace', p_replace), p_by);
  return jsonb_build_object('ok', true, 'in', v_n, 'off', v_off, 'n', (select count(*) from sub.pkg_model where active), 'n_sub', (select count(*) from sub.pkg_model where active and sub_ok));
end $$;
create or replace function public.fn_sub_pkg_import(p_rows jsonb, p_replace boolean default false) returns jsonb
language plpgsql security definer set search_path to 'pg_catalog','public' as $$
begin
  if core.f_role() <> 'admin' then raise exception '스마트 패키지 모델은 관리자만 바꿀 수 있습니다' using errcode = '42501'; end if;
  return sub.f_pkg_import(p_rows, p_replace, core.f_sdp_actor());
end $$;
-- 모델 목록 보기 (관리자 · 품목별 · dps = 지금 구독 운영 중인 모델과 맞는가)
create or replace function public.fn_sub_pkg_list(p_q text default null) returns jsonb
language sql stable security definer set search_path to 'pg_catalog','public' as $$
  select case when core.f_role() <> 'admin' then null else
    (select coalesce(jsonb_agg(jsonb_build_object('model', model, 'cat', cat, 'grp', grp, 'sub_ok', sub_ok, 'bonus', bonus,
              'dps', exists (select 1 from dps.sub_model d where d.active and (d.model = m.model or m.model like d.model || '%'))) order by cat, grp, model), '[]'::jsonb)
       from sub.pkg_model m where active and (coalesce(p_q,'') = '' or model ilike '%'||p_q||'%' or cat ilike '%'||p_q||'%' or coalesce(grp,'') ilike '%'||p_q||'%')) end;
$$;
revoke all on function sub.f_pkg_import(jsonb, boolean, text), public.fn_sub_pkg_import(jsonb, boolean), public.fn_sub_pkg_list(text) from public, anon, authenticated;
grant execute on function public.fn_sub_pkg_import(jsonb, boolean) to authenticated, service_role;
