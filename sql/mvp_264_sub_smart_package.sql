-- ── 7. (mvp_264b) 본사 스마트 패키지 표기 ↔ DPS 모델번호 맞추기 — 설치형·색상·세트 꼬리표가 달라 그대로는 618개 중 211개만 맞았다 ──
--   본사: AF80F19D25WN · AR60F07D11WNKO · RQ33DB7441AP · DW80F75K1UAP   DPS: AF80F19D25WT/WZ · AR60F07D11WT · RQ33DB7441APEW · DW80F75K1USWS
--   규칙: 같다 / 한쪽이 다른 쪽의 앞부분 / 앞부분이 9자 이상 같고 짧은 쪽 길이 −1 이상 / 'AP'·'APG'(패널 선택형)를 뗀 앞부분 — sub_bundle.js pkgMatch 와 같다
--   (mvp_264c) 앞 6자가 같은 짝에서만 본다 — 618 × 1,131 쌍 전부 f_lcp 를 돌리면 statement timeout. 부르는 쪽도 left(model,6) 로 먼저 거른다
create or replace function sub.f_pkg_match(s text, d text) returns boolean
language sql immutable as $$
  select left(s, 6) = left(d, 6) and (
         s = d or starts_with(d, s) or (length(d) >= 8 and starts_with(s, d))
      or (s ~ '(AP|APG)$' and length(regexp_replace(s, '(AP|APG)$', '')) >= 8 and starts_with(d, regexp_replace(s, '(AP|APG)$', '')))
      or (sub.f_lcp(s, d) >= 9 and sub.f_lcp(s, d) >= least(length(s), length(d)) - 1));
$$;
revoke all on function sub.f_pkg_match(text, text) from public, anon, authenticated;

create or replace function public.fn_sub_pkg_list(p_q text default null) returns jsonb
language sql stable security definer set search_path to 'pg_catalog','public' as $$
  select case when core.f_role() <> 'admin' then null else
    (with d as (select distinct model, left(model, 6) k6 from dps.sub_model where active)
     select coalesce(jsonb_agg(jsonb_build_object('model', model, 'cat', cat, 'grp', grp, 'sub_ok', sub_ok, 'bonus', bonus,
              'dps', (select string_agg(d.model, ' ') from d where d.k6 = left(m.model, 6) and sub.f_pkg_match(m.model, d.model))) order by cat, grp, model), '[]'::jsonb)
       from sub.pkg_model m where active and (coalesce(p_q,'') = '' or model ilike '%'||p_q||'%' or cat ilike '%'||p_q||'%' or coalesce(grp,'') ilike '%'||p_q||'%')) end;
$$;

