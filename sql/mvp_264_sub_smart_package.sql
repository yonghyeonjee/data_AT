-- mvp_264 (2026-11-03) 구독 멤버십 포인트 기준금액을 제품분(product_fee)으로 · 다품목 혜택 = 11월 스마트 패키지 정액표 · 선납 상한 보완
--
-- 1) 포인트 기준금액 — 삼성닷컴 구독 계산기는 "적립 예정 멤버십 포인트" 를 총 구독금액이 아니라 제품분 금액(aiscPrdSsbPrc = DPS product_fee · 무상수리료 제외)에
--    정률 6% + 기본 0.1% 를 곱하고, 선납·카드를 바꿔도 변하지 않는다 (AI 콤보 WD90H25AHS 6년: 6,066,720 × 6.1% = 370,069P).
--    우리는 총액(total_fee)으로 수집하고(386,978P) 화면은 할인 뒤 결제 예상액에 곱해(367,171P 이하) 둘 다 달랐다.
--    → fn_sub_dps_export items 에 product_fee 를 10번째로 싣고(build_sub.mjs 가 요금제 행 5번째 값으로), 수집 대상(fn_sub_point_targets)의 price 도 product_fee 로.
-- 2) 다품목 — 시흥점 "11월 스마트 패키지" (본사 정액표): 대상 모델을 2품목 이상 동시 구매(구독 대상 모델은 구독도 포함)하면 품목 수별 정액 포인트
--    (2품목 10만 · 3품목 15만 · 4품목 25만 · 5품목 65만 … 22품목 600만). TV 와 2nd TV 는 다른 품목. 『3만 혜택』 모델(모니터·식기세척기 10개)은 일반 구매 때만 3만P 라 구독 계산에는 안 넣는다.
--    → 표 sub.pkg_model(모델·품목·모델군·구독 대상·3만 혜택) + 정책 키 bundle {kind:'package', tiers, min, from, to, text}
--    → 배포 bundle 에 cats · models(구독 대상만 · 모델 → 품목 번호) 를 붙여 다품목 계산기(sub_bundle.js)가 품목 수를 세어 정액을 보여 준다.
--    → 관리자: fn_sub_policy_save('bundle', …) 로 정액표·기간, fn_sub_pkg_import 로 모델 목록 교체 (admin.html 품목 › 구독 혜택 정책 › 다품목 스마트 패키지)
-- 3) 선납 상한 — DPS 기준 제습기 30% · 갤럭시 탭 40% 가 정책 maxByCat 에 없어 기본 50% 가 열려 있었다 → 추가 (갤럭시 북 50% 도 명시).
-- 적용: MCP apply_migration. 적용 뒤 sub.policy 저장 트리거가 배포를 건다. 화면 쪽은 tools/sub/build_sub.mjs · sdp/sub/sub_tab.js · sdp/sub/sub_bundle.js · admin.html 같이 바뀜.

-- ── 1. DPS 내보내기에 product_fee (items 10번째) ──
-- items 원소: [model, category, seg, term_months, service, visit_cycle, total_fee, monthly_fee, prepay_ok, product_fee]
create or replace function public.fn_sub_dps_export() returns jsonb
language sql stable security definer set search_path to 'pg_catalog','public' as $$
  with f as (select fetch_id, finished_at, rows from dps.sub_model_fetch where finished_at is not null order by finished_at desc limit 1),
       a as (select * from dps.sub_model where active)
  select jsonb_build_object(
    'fetch_id',   (select fetch_id from f),
    'fetched_at', (select finished_at from f),
    'fetch_rows', (select rows from f),
    'rows',       (select count(*) from a),
    'models',     (select count(distinct model) from a),
    'items',      coalesce((select jsonb_agg(jsonb_build_array(model, category, seg, term_months, service, visit_cycle, total_fee, monthly_fee,
                      exists(select 1 from jsonb_array_elements(prepay) e where coalesce((e->>'ratio')::int, 0) > 0),
                      case when coalesce(product_fee, 0) > 0 and product_fee < total_fee then product_fee end) order by row_no, model, term_months, service, visit_cycle)
                    from a), '[]'::jsonb));
$$;

-- ── 1b. 포인트 수집 대상의 기준금액 = 최장 약정 최저 제품분 금액 (없으면 총액) ──
create or replace function public.fn_sub_point_targets(p_all boolean default false, p_limit int default 3000, p_key text default null, p_offset int default 0)
returns table(model text, term_months int, price int, goods_id text)
language plpgsql stable security definer set search_path to 'pg_catalog','public' as $$
begin
  if not sub.f_point_api_ok(p_key) then raise exception '키가 맞지 않습니다' using errcode = '42501'; end if;
  return query
    with a as (select s.model, max(s.term_months) mt from dps.sub_model s where s.active and s.term_months > 0 group by s.model),
         pr as (select a.model, a.mt, min(coalesce(nullif(s.product_fee, 0), s.total_fee))::int price   -- 삼성닷컴 membershipPolicy 의 price = 제품분(aiscPrdSsbPrc) · mvp_264
                  from a join dps.sub_model s on s.model = a.model and s.active and s.term_months = a.mt
                 where s.total_fee > 0 group by a.model, a.mt)
    select pr.model, pr.mt, pr.price, coalesce(mp.goods_id, c.goods_id)
      from pr
      left join sub.model_point mp on mp.model = pr.model
      left join sub.model_point_check c on c.model = pr.model
     where p_all
        or c.model is null
        or (c.found and c.checked_at < now() - interval '6 days')
        or (not c.found and c.checked_at < now() - least(7 * (1 + c.miss_count / 3), 30) * interval '1 day')
     order by c.checked_at nulls first, pr.model
     limit least(p_limit, 1000) offset greatest(coalesce(p_offset, 0), 0);
end $$;

-- ── 2. 스마트 패키지 대상 모델 ──
create table if not exists sub.pkg_model (
  model      text primary key,                 -- 본사 표기 그대로 (KQ85QND900FXKR · RF85DB95A2APW …) · DPS 모델번호와 같거나 그 앞부분이 같다
  cat        text not null,                    -- 본사 품목 (TV · 2nd TV · 냉장고 · 냉동고 · 와인 · 변온 · PC(구독) …) — 품목 수는 이 이름으로 센다
  grp        text,                             -- 모델군 (Neo QLED 8K · 4도어 허브 …)
  sub_ok     boolean not null default false,   -- 구독으로 샀을 때도 품목 수에 들어가는 모델 (표의 '구독' · 노란 음영)
  bonus      boolean not null default false,   -- 『3만 혜택』 모델 (일반 구매 때만 3만P · 구독 계산에는 안 쓴다)
  active     boolean not null default true,    -- 다음 달 표로 바꿀 때 빠진 모델은 끈다 (기록은 남긴다)
  note       text,
  updated_at timestamptz not null default now(),
  updated_by text
);
