-- ── 3. 정책 키 bundle 검사 (f_policy_check · mvp_253 본체 + bundle) ──
create or replace function sub.f_policy_check(p_key text, p_value jsonb) returns void
language plpgsql immutable as $$
declare x jsonb; k text;
  procedure_rate text := '0 이상 1 미만 소수여야 합니다 (5% → 0.05)';
begin
  if p_key = 'autopay' then
    if jsonb_typeof(p_value->'rate') <> 'number' or (p_value->>'rate')::numeric < 0 or (p_value->>'rate')::numeric >= 1 then
      raise exception 'autopay.rate: %', procedure_rate using errcode = '22023'; end if;
    if coalesce(p_value->>'label','') !~ '\{rate\}' then
      raise exception 'autopay.label 에는 {rate} 자리가 있어야 합니다' using errcode = '22023'; end if;
  elsif p_key = 'prepay' then
    if jsonb_typeof(p_value->'steps') <> 'array' then raise exception 'prepay.steps 는 목록이어야 합니다' using errcode = '22023'; end if;
    for x in select * from jsonb_array_elements(p_value->'steps') loop
      if jsonb_typeof(x) <> 'number' or x::text::numeric <= 0 or x::text::numeric >= 1 then
        raise exception 'prepay.steps: % — %', x, procedure_rate using errcode = '22023'; end if;
      if not (p_value->'rates') ? (x::text) then
        raise exception 'prepay.rates: 선납 % 의 할인율이 없습니다', x using errcode = '22023'; end if;
    end loop;
    for k, x in select * from jsonb_each(coalesce(p_value->'rates','{}'::jsonb)) loop
      if jsonb_typeof(x) <> 'number' or x::text::numeric < 0 or x::text::numeric >= 1 then
        raise exception 'prepay.rates.%: %', k, procedure_rate using errcode = '22023'; end if;
    end loop;
    if p_value ? 'defaultMax' and (jsonb_typeof(p_value->'defaultMax') <> 'number' or (p_value->>'defaultMax')::numeric <= 0 or (p_value->>'defaultMax')::numeric > 1) then
      raise exception 'prepay.defaultMax: %', procedure_rate using errcode = '22023'; end if;
    for k, x in select * from jsonb_each(coalesce(p_value->'maxByCat','{}'::jsonb)) loop
      if jsonb_typeof(x) <> 'number' or x::text::numeric < 0 or x::text::numeric > 1 then
        raise exception 'prepay.maxByCat.%: %', k, procedure_rate using errcode = '22023'; end if;
    end loop;
    for x in select * from jsonb_array_elements(coalesce(p_value->'maxByName','[]'::jsonb)) loop
      if coalesce(x->>'cat','') = '' or coalesce(x->>'contains','') = '' or jsonb_typeof(x->'max') <> 'number' then
        raise exception 'prepay.maxByName: cat · contains · max 가 모두 있어야 합니다 (%)', x using errcode = '22023'; end if;
    end loop;
    if p_value ? 'notes' and jsonb_typeof(p_value->'notes') <> 'array' then raise exception 'prepay.notes 는 문장 목록이어야 합니다' using errcode = '22023'; end if;
  elsif p_key = 'texts' then
    if p_value ? 'points' and jsonb_typeof(p_value->'points') <> 'array' then raise exception 'texts.points 는 문장 목록이어야 합니다' using errcode = '22023'; end if;
    if p_value ? 'notice' and jsonb_typeof(p_value->'notice') <> 'string' then raise exception 'texts.notice 는 글이어야 합니다' using errcode = '22023'; end if;
  elsif p_key = 'card_notes' then
    if jsonb_typeof(p_value) <> 'array' then raise exception 'card_notes 는 문장 목록이어야 합니다' using errcode = '22023'; end if;
  elsif p_key = 'defaults' then
    if jsonb_typeof(p_value) <> 'object' then raise exception 'defaults 는 항목 묶음이어야 합니다' using errcode = '22023'; end if;
    if coalesce(btrim(p_value->>'card'),'') = '' then raise exception 'defaults.card: 기본 제휴카드 이름이 비었습니다 (카드 금액표의 이름과 같게 · 예: 삼성카드)' using errcode = '22023'; end if;
    if p_value ? 'tier' and jsonb_typeof(p_value->'tier') <> 'string' then raise exception 'defaults.tier: 실적 구간은 글자여야 합니다 (예: 30만↑ · 비우면 가장 낮은 구간)' using errcode = '22023'; end if;
    if coalesce(p_value->>'consultUrl','') !~ '^(/|https://)' then raise exception 'defaults.consultUrl: 상담 신청 주소는 / 또는 https:// 로 시작해야 합니다' using errcode = '22023'; end if;
    if coalesce(p_value->>'tel','') !~ '^[0-9-]*$' then raise exception 'defaults.tel: 전화번호는 숫자와 - 만 (예: 031-8042-3166 · 비우면 전화 버튼 없음)' using errcode = '22023'; end if;
  elsif p_key = 'bundle' then
    -- 다품목 혜택 (mvp_264) · kind 'package': 품목 수별 정액 {tiers: {"2": 100000, …}, min, from, to, text, name} · kind 'rate': 월 납부액 비율 {rate, min}
    if jsonb_typeof(p_value) <> 'object' then raise exception 'bundle 은 항목 묶음이어야 합니다' using errcode = '22023'; end if;
    if coalesce(p_value->>'kind','package') not in ('package','rate') then raise exception 'bundle.kind 는 package(품목 수별 정액) 또는 rate(비율) 여야 합니다' using errcode = '22023'; end if;
    if coalesce(p_value->>'kind','package') = 'package' then
      if jsonb_typeof(p_value->'tiers') <> 'object' or p_value->'tiers' = '{}'::jsonb then raise exception 'bundle.tiers: 품목 수별 금액표가 비었습니다 ({"2": 100000, "3": 150000, …})' using errcode = '22023'; end if;
      for k, x in select * from jsonb_each(p_value->'tiers') loop
        if k !~ '^\d+$' or k::int < 2 then raise exception 'bundle.tiers: 품목 수는 2 이상 정수여야 합니다 (현재 %)', k using errcode = '22023'; end if;
        if jsonb_typeof(x) <> 'number' or x::text::numeric <= 0 or x::text::numeric <> floor(x::text::numeric) then raise exception 'bundle.tiers.%: 금액은 양의 정수(원)여야 합니다', k using errcode = '22023'; end if;
      end loop;
    else
      if jsonb_typeof(p_value->'rate') <> 'number' or (p_value->>'rate')::numeric <= 0 or (p_value->>'rate')::numeric >= 1 then raise exception 'bundle.rate: %', procedure_rate using errcode = '22023'; end if;
    end if;
    if p_value ? 'min' and (jsonb_typeof(p_value->'min') <> 'number' or (p_value->>'min')::numeric < 2) then raise exception 'bundle.min: 최소 품목 수는 2 이상 정수여야 합니다' using errcode = '22023'; end if;
    perform sub.f_date(p_value->>'from', 'bundle.from'); perform sub.f_date(p_value->>'to', 'bundle.to');
    if coalesce(p_value->>'from','') <> '' and coalesce(p_value->>'to','') <> '' and (p_value->>'to')::date < (p_value->>'from')::date then raise exception 'bundle: 종료일이 시작일보다 앞입니다' using errcode = '22023'; end if;
  else
    raise exception '모르는 정책 키입니다: % (autopay · prepay · texts · card_notes · defaults · bundle)', p_key using errcode = '22023';
  end if;
end $$;

-- ── 4. 배포 파일에 bundle (정책 + cats + 구독 대상 모델 → 품목 번호) · 관리자 보기에 pkg 요약 ──
create or replace function sub.f_bundle_export() returns jsonb
language sql stable security definer set search_path to 'pg_catalog','public' as $$
  with b as (select value from sub.policy where key = 'bundle'),
       m as (select model, cat from sub.pkg_model where active and sub_ok),
       c as (select cat, row_number() over (order by min(model)) - 1 idx from m group by cat)
  select case when (select value from b) is null then null else
    (select value from b) || jsonb_build_object(
      'cats', coalesce((select jsonb_agg(cat order by idx) from c), '[]'::jsonb),
      'models', coalesce((select jsonb_object_agg(m.model, c.idx) from m join c on c.cat = m.cat), '{}'::jsonb)) end;
$$;
revoke all on function sub.f_bundle_export() from public, anon, authenticated;

create or replace function sub.f_policy_export()
returns jsonb language sql stable security definer set search_path to 'pg_catalog','public' as $$
  with p as (select key, value from sub.policy)
  select jsonb_strip_nulls(jsonb_build_object(
    'ver', sub.f_policy_ver(),
    'defaults', (select value from p where key = 'defaults'),
    'autopay', (select value from p where key = 'autopay'),
    'prepay',  (select value from p where key = 'prepay'),
    'texts',   (select value from p where key = 'texts'),
    'cardNotes', coalesce((select value from p where key = 'card_notes'), '[]'::jsonb),
    'cards', (select coalesce(jsonb_object_agg(card, jsonb_strip_nulls(jsonb_build_object(
                'notes', case when cardinality(notes) > 0 then to_jsonb(notes) end,
                'from', to_char(from_d,'YYYY-MM-DD'), 'to', to_char(to_d,'YYYY-MM-DD'), 'hidden', case when hidden then true end))), '{}'::jsonb)
              from sub.card_policy),
    'promos', (select coalesce(jsonb_agg(jsonb_strip_nulls(jsonb_build_object(
                'text', text, 'from', to_char(from_d,'YYYY-MM-DD'), 'to', to_char(to_d,'YYYY-MM-DD'),
                'cats', case when cardinality(cats) > 0 then to_jsonb(cats) end,
                'models', case when cardinality(models) > 0 then to_jsonb(models) end,
                'goods', case when cardinality(goods) > 0 then to_jsonb(goods) end,
                'months', months, 'amount', amount, 'amounts', amounts,
                'maxTerm', case when (months is not null or amount is not null or amounts is not null) and not max_term_only then false end)) order by sort, id), '[]'::jsonb)
               from sub.promo where active and (to_d is null or to_d >= (now() at time zone 'Asia/Seoul')::date - 1)),
    'points', sub.f_point_export(),
    'bundle', sub.f_bundle_export(),
    'overrides', sub.f_price_override_live()));
$$;

-- 정책 판 이름에 스마트 패키지 모델 변경 시각도 넣는다 (목록만 바꿔도 새 판)
create or replace function sub.f_policy_ver() returns text
language sql stable security definer set search_path to 'pg_catalog','public' as $$
  select to_char(coalesce(greatest((select max(updated_at) from sub.policy), (select max(updated_at) from sub.card_policy), (select max(updated_at) from sub.promo),
                                   (select max(updated_at) from sub.pkg_model)), now())
                 at time zone 'Asia/Seoul', 'YYMMDD-HH24MI');
$$;

-- f_policy_view 에 'pkg' 요약 (본문 치환 — 'ver', sub.f_policy_ver() 앞에 끼운다)
do $outer$
declare v_src text; v_new text;
begin
  select pg_get_functiondef(p.oid) into v_src from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'sub' and p.proname = 'f_policy_view';
  if v_src is null then raise exception 'sub.f_policy_view 가 없습니다'; end if;
  if v_src like '%''pkg'',%' then raise notice 'f_policy_view 에 pkg 가 이미 있습니다'; return; end if;
  v_new := replace(v_src, $q$    'ver', sub.f_policy_ver(),$q$,
    $q$    'pkg', (select jsonb_build_object(
                 'n', count(*), 'n_sub', count(*) filter (where sub_ok), 'n_bonus', count(*) filter (where bonus),
                 'n_dps', count(*) filter (where sub_ok and exists (select 1 from dps.sub_model d where d.active and (d.model = m.model or m.model like d.model || '%'))),
                 'cats', (select coalesce(jsonb_agg(jsonb_build_object('cat', cat, 'n', n, 'n_sub', n_sub) order by cat), '[]'::jsonb)
                            from (select cat, count(*) n, count(*) filter (where sub_ok) n_sub from sub.pkg_model where active group by cat) t),
                 'updated', to_char(max(updated_at) at time zone 'Asia/Seoul','YYYY-MM-DD HH24:MI'))
               from sub.pkg_model m where active),
    'ver', sub.f_policy_ver(),$q$);
  if v_new = v_src then raise exception 'f_policy_view 치환 지점을 못 찾았습니다'; end if;
  execute v_new;
end $outer$;

